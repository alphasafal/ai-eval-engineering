import { SEMANTIC_DIMENSIONS } from "../graders/semantic-grader";
import type { Comparison } from "../eval/compare";
import { FAILURE_TYPES, type EvalRun } from "../eval/types";
import { formatDelta, formatUnit } from "./format";

/** Static, dependency-free HTML dashboard generated from result files. */

const esc = (value: unknown) =>
  String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");

const pct = (v: number | null) => formatUnit("percent", v);

export function renderHtmlReport(runs: EvalRun[], comparison: Comparison | null, generatedAt = new Date()): string {
  const isMock = runs.some((r) => r.meta.isMock);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>AI Eval Report — AcmePay Support Agent</title>
<style>${STYLES}</style>
</head>
<body>
<main>
  <header>
    <div>
      <h1>AI Eval Report</h1>
      <p class="muted">AcmePay support agent · ${esc(runs[0]?.meta.caseCount ?? 0)} cases · generated ${esc(generatedAt.toISOString())}</p>
    </div>
    ${isMock ? `<span class="pill warn">Mock provider demonstration — responses are simulated; metrics are computed from them</span>` : ""}
  </header>
  ${comparison ? renderComparison(comparison) : ""}
  ${runs.map(renderRun).join("\n")}
  <footer class="muted">Generated by ai-eval-engineering. Raw data: results/*.json</footer>
</main>
</body>
</html>
`;
}

function renderComparison(cmp: Comparison): string {
  const rows = cmp.rows
    .map((r) => {
      const width = r.unit === "percent" ? (v: number | null) => `${Math.round((v ?? 0) * 100)}%` : null;
      const bar = (v: number | null, cls: string) => (width ? `<div class="bar ${cls}" style="width:${width(v)}"></div>` : "");
      return `<tr>
        <td>${esc(r.label)}</td>
        <td class="num">${esc(formatUnit(r.unit, r.baseline))}${bar(r.baseline, "a")}</td>
        <td class="num">${esc(formatUnit(r.unit, r.candidate))}${bar(r.candidate, "b")}</td>
        <td class="num ${r.verdict}">${esc(formatDelta(r.unit, r.delta))}</td>
      </tr>`;
    })
    .join("");
  const changes = [
    ...cmp.regressed.map((c) => `<li class="regressed">↓ <code>${esc(c.caseId)}</code> regressed: ${esc(c.candidateReasons.join("; "))}</li>`),
    ...cmp.stillFailing.map((c) => `<li>· <code>${esc(c.caseId)}</code> still failing: ${esc(c.candidateReasons.join("; "))}</li>`),
  ].join("");
  return `<section>
    <h2>${esc(cmp.baseline.version.toUpperCase())} vs ${esc(cmp.candidate.version.toUpperCase())}</h2>
    ${cmp.sameDataset ? "" : `<p class="pill fail">Runs used different datasets — deltas are not comparable</p>`}
    <div class="scroll"><table>
      <thead><tr><th>Metric</th><th class="num" title="${esc(cmp.baseline.label)}">${esc(cmp.baseline.version.toUpperCase())}</th><th class="num" title="${esc(cmp.candidate.label)}">${esc(cmp.candidate.version.toUpperCase())}</th><th class="num">Change</th></tr></thead>
      <tbody>${rows}
        <tr><td>Release gate</td><td class="num">${gatePill(cmp.baseline.gatePassed)}</td><td class="num">${gatePill(cmp.candidate.gatePassed)}</td><td></td></tr>
      </tbody>
    </table></div>
    <p><strong class="improved">${cmp.fixed.length} fixed</strong> · <strong class="${cmp.regressed.length ? "regressed" : ""}">${cmp.regressed.length} regressed</strong> · ${cmp.stillFailing.length} still failing</p>
    ${changes ? `<ul class="changes">${changes}</ul>` : ""}
  </section>`;
}

function renderRun(run: EvalRun): string {
  const m = run.metrics;
  const card = (label: string, value: string, status?: string) =>
    `<div class="card ${status ?? ""}"><div class="label">${esc(label)}</div><div class="value">${esc(value)}</div></div>`;
  const statusOf = (metric: string) => run.gate.criteria.find((c) => c.metric === metric)?.status;
  const failureCounts = FAILURE_TYPES.map((t) => [t, run.failures.groups[t].length] as const).filter(([, n]) => n > 0);
  const maxCount = Math.max(1, ...failureCounts.map(([, n]) => n));

  return `<section>
    <h2>${esc(run.meta.promptLabel)} ${gatePill(run.gate.passed)}</h2>
    <p class="muted">${esc(run.meta.provider)} · ${esc(run.meta.model)} · judge: ${esc(run.meta.judgeMode)} · latency: ${esc(m.latency.source)}</p>

    <h3>Outcome quality</h3>
    <div class="cards">
      ${card("Pass rate", `${pct(m.passRate)} (${m.passedCases}/${m.totalCases})`)}
      ${card("Intent accuracy", pct(m.intentAccuracy), statusOf("intentAccuracy"))}
      ${card("Action accuracy", pct(m.actionAccuracy), statusOf("actionAccuracy"))}
      ${card("Escalation accuracy", pct(m.escalationAccuracy), statusOf("escalationAccuracy"))}
      ${card("Schema validity", pct(m.schemaValidity), statusOf("schemaValidity"))}
      ${card("Safety pass rate", pct(m.safetyPassRate), statusOf("safetyPassRate"))}
      ${card("Semantic score", formatUnit("score", m.semantic?.overall ?? null), statusOf("semanticOverall"))}
    </div>
    ${m.semantic?.averages ? `<p class="muted small">Semantic (${esc(m.semantic.mode)} judge): ${SEMANTIC_DIMENSIONS.map((d) => `${esc(d)} ${m.semantic!.averages![d].toFixed(2)}`).join(" · ")}</p>` : ""}

    <div class="grid2">
      <div>
        <h3>Execution quality</h3>
        <table><tbody>
          <tr><td>Efficient trajectories</td><td class="num">${pct(m.trajectory.efficientRate)}</td></tr>
          <tr><td>Avg tool calls / task</td><td class="num">${formatUnit("count", m.trajectory.avgToolCalls)}</td></tr>
          <tr><td>Avg model calls / task</td><td class="num">${formatUnit("count", m.trajectory.avgModelCalls)}</td></tr>
          <tr><td>Cases with redundant tools</td><td class="num">${pct(m.trajectory.redundantToolCallRate)}</td></tr>
          <tr><td>Cases with invalid tools</td><td class="num">${pct(m.trajectory.invalidToolCallRate)}</td></tr>
          <tr><td>Retry rate</td><td class="num">${pct(m.trajectory.retryRate)}</td></tr>
        </tbody></table>
      </div>
      <div>
        <h3>Latency &amp; cost</h3>
        <table><tbody>
          <tr><td>Average latency</td><td class="num">${formatUnit("ms", m.latency.avgMs)}</td></tr>
          <tr><td>P50 / P95 latency</td><td class="num">${formatUnit("ms", m.latency.p50Ms)} / ${formatUnit("ms", m.latency.p95Ms)}</td></tr>
          <tr><td>Avg tokens / task</td><td class="num">${Math.round(m.tokens.avgPerCase)}</td></tr>
          <tr><td>Avg cost / task</td><td class="num">${formatUnit("usd", m.cost.avgPerTaskUsd)}</td></tr>
          <tr><td>Total estimated cost</td><td class="num">${formatUnit("usd", m.cost.totalUsd)}</td></tr>
        </tbody></table>
        ${run.meta.pricingNote ? `<p class="muted small">${esc(run.meta.pricingNote)}</p>` : ""}
      </div>
    </div>

    <h3>Release gate</h3>
    <ul class="gate">${run.gate.criteria.map((c) => `<li class="${c.status}">${c.status === "pass" ? "✓" : c.status === "fail" ? "✗" : "–"} ${esc(c.message)}</li>`).join("")}</ul>

    <h3>Failure breakdown</h3>
    ${failureCounts.length === 0 ? `<p>No failures.</p>` : `<div class="breakdown">${failureCounts
      .map(([t, n]) => `<div class="brow"><span>${esc(t.replaceAll("_", " "))}</span><div class="track"><div class="bar fail" style="width:${(n / maxCount) * 100}%"></div></div><span class="num">${n}</span></div>`)
      .join("")}</div>`}
    ${run.failures.patterns.length ? `<h4>Patterns</h4><ul>${run.failures.patterns.map((p) => `<li>${esc(p)}</li>`).join("")}</ul>` : ""}

    ${renderFailedCases(run)}
  </section>`;
}

function renderFailedCases(run: EvalRun): string {
  const failed = run.records.filter((r) => !r.passed);
  if (failed.length === 0) return "";
  const fmt = (i: string | null, a: string | null, e: boolean | null) => (i === null ? `<em>no valid output</em>` : `${esc(i)}<br>${esc(a)}<br>escalate=${esc(e)}`);
  const rows = failed
    .map(
      (r) => `<tr>
      <td><code>${esc(r.caseId)}</code><div class="muted small">${esc(r.category)}</div></td>
      <td>${esc(r.input)}</td>
      <td class="small">${fmt(r.expectedIntent, r.expectedAction, r.expectedEscalate)}</td>
      <td class="small">${fmt(r.intent, r.action, r.escalate)}</td>
      <td class="small">${esc(r.failureReasons.join("; "))}${r.output ? `<details><summary>response</summary>${esc(r.output.response)}</details>` : ""}</td>
    </tr>`,
    )
    .join("");
  return `<details class="failed" ${failed.length <= 12 ? "open" : ""}>
    <summary><h3>Failed cases (${failed.length})</h3></summary>
    <div class="scroll"><table class="cases">
      <thead><tr><th>Case</th><th>Input</th><th>Expected</th><th>Actual</th><th>Why</th></tr></thead>
      <tbody>${rows}</tbody>
    </table></div>
  </details>`;
}

